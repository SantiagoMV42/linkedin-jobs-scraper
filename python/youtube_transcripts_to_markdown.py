"""Save YouTube transcripts as Markdown files (one per video), ready for notes, LLMs or RAG.

pip install apify-client
APIFY_TOKEN=... python youtube_transcripts_to_markdown.py https://youtu.be/aircAruvnKk https://www.youtube.com/shorts/...
"""
import os
import re
import sys
from pathlib import Path

from apify_client import ApifyClient

videos = sys.argv[1:] or ["https://www.youtube.com/watch?v=aircAruvnKk"]
client = ApifyClient(os.environ["APIFY_TOKEN"])
run = client.actor("santiagomv/youtube-transcripts").call(run_input={"videos": videos, "language": "en"})

out = Path("transcripts")
out.mkdir(exist_ok=True)
for v in client.dataset(run["defaultDatasetId"]).iterate_items():
    name = re.sub(r"[^\w-]+", "-", v["title"]).strip("-")[:80] or v["videoId"]
    path = out / f"{name}.md"
    path.write_text(
        f"# {v['title']}\n\n{v['channelName']} · {v['url']} · {v['language']}"
        f"{' (auto-generated)' if v['isAutoGenerated'] else ''}\n\n{v['transcriptWithTimestamps']}\n",
        encoding="utf-8",
    )
    print(f"{path} ({v['wordCount']} words)")

failed = client.key_value_store(run["defaultKeyValueStoreId"]).get_record("FAILURES")
for f in (failed or {}).get("value") or []:
    print("no transcript:", f.get("url") or f.get("input"), "-", f["error"])
